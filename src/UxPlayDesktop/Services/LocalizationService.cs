    public string CurrentLanguage
    {
        get => _currentLanguage;
        set
        {
            if (_currentLanguage != value)
            {
                _currentLanguage = value;
                OnPropertyChanged();
                OnPropertyChanged("Item[]");
            }
        }
    }

    public string this[string key] => GetString(key);

    public LocalizationService()
    {
        InitializeDictionaries();
    }

    public void SetLanguage(string languageCode)
    {
        CurrentLanguage = languageCode;
    }

    private string ResolveEffectiveLanguage()
    {
        if (CurrentLanguage != "auto" && !string.IsNullOrWhiteSpace(CurrentLanguage))
        {
            return CurrentLanguage;
        }

        var culture = CultureInfo.CurrentUICulture.Name;
        if (culture.StartsWith("es", StringComparison.OrdinalIgnoreCase)) return "es";
        if (culture.StartsWith("pt-BR", StringComparison.OrdinalIgnoreCase)) return "pt-BR";
        if (culture.StartsWith("pt", StringComparison.OrdinalIgnoreCase)) return "pt-PT";
        if (culture.StartsWith("fr", StringComparison.OrdinalIgnoreCase)) return "fr";
        if (culture.StartsWith("de", StringComparison.OrdinalIgnoreCase)) return "de";
        if (culture.StartsWith("it", StringComparison.OrdinalIgnoreCase)) return "it";
        if (culture.StartsWith("ru", StringComparison.OrdinalIgnoreCase)) return "ru";
        if (culture.StartsWith("pl", StringComparison.OrdinalIgnoreCase)) return "pl";
        if (culture.StartsWith("nl", StringComparison.OrdinalIgnoreCase)) return "nl";
        if (culture.StartsWith("uk", StringComparison.OrdinalIgnoreCase)) return "uk";
        if (culture.StartsWith("sv", StringComparison.OrdinalIgnoreCase)) return "sv";
        if (culture.StartsWith("zh", StringComparison.OrdinalIgnoreCase)) return "zh-CN";
        if (culture.StartsWith("ja", StringComparison.OrdinalIgnoreCase)) return "ja";
        if (culture.StartsWith("ko", StringComparison.OrdinalIgnoreCase)) return "ko";

        return "en";
    }

    public string GetString(string key)
    {
        var lang = ResolveEffectiveLanguage();
        if (_translations.TryGetValue(lang, out var dict) && dict.TryGetValue(key, out var val))
        {
            return val;
        }

        // Fallback to English
        if (_translations.TryGetValue("en", out var enDict) && enDict.TryGetValue(key, out var enVal))
        {
            return enVal;
        }

        return key;
    }

    protected void OnPropertyChanged([CallerMemberName] string? propertyName = null)
    {
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
    }

